/* ============================================
   SIA7: NLP TARGET EXTRACTOR
   Extrae el nombre de la función tolerando
   typos, faltas de ortografía y palabras de relleno.
============================================ */
function extractTargetName(intentText, actionRegex) {
    if (!actionRegex.test(intentText)) return null;
    
    // Cortamos la cadena a partir de la acción detectada
    let remainder = intentText.substring(intentText.search(actionRegex));
    remainder = remainder.replace(actionRegex, '');
    
    // Limpiamos la "basura" léxica y errores comunes
    remainder = remainder.replace(/\b(la|el|una|un|funci[oó]n|fncion|function|m[eé]todo|de|en|el|archivo|file|script)\b/gi, ' ');
    
    // El primer término limpio que quede debe ser el target
    const words = remainder.trim().split(/\s+/);
    const target = words[0] ? words[0].replace(/[^a-zA-Z0-9_]/g, '') : null;
    
    return target && target.length > 0 ? target : "autoGeneratedSIA7Function";
}

window.buildRepairPatch =
async function(
    repairContext = {}
) {

    try {

        console.log(
            "🧠 [REPAIR_TRANSLATOR_START]",
            repairContext
        );

        const {
            targetFile,
            userIntent,
            source
        } = repairContext;

        if (!targetFile) {
            throw new Error(
                "TARGET_FILE_REQUIRED"
            );
        }

        let currentSource = source;

        // 🔥 FIX: si "source" no parece código fuente, cargar el archivo real
if (
    !currentSource ||
    typeof currentSource !== "string" ||
    !currentSource.includes("function") &&
    !currentSource.includes("export") &&
    !currentSource.includes("window.")
) {
    const loaded = await window.loadRepoContext(targetFile);

    if (!loaded?.ok) {
        throw new Error("SOURCE_LOAD_FAIL");
    }

    currentSource = loaded.source;
}

        if (!currentSource) {
            const loaded =
                await window
                    .loadRepoContext(
                        targetFile
                    );

            if (!loaded?.ok) {
                throw new Error(
                    loaded?.error ||
                    "SOURCE_LOAD_FAIL"
                );
            }

            currentSource = loaded.source;
        }

        let intent =
            String(
                userIntent || ""
            ).toLowerCase();

        // 🔥 AISLAMIENTO DE NOMBRE DE ARCHIVO
        // Evitamos que palabras dentro del nombre del archivo (ej. "replace" en "test-replace.js")
        // activen estrategias incorrectas.
        if (targetFile) {
            const fileNameLower = targetFile.toLowerCase();
            const fileNameWithoutExt = fileNameLower.split('.')[0];
            
            // Removemos el nombre exacto del archivo de la oración
            intent = intent.replace(new RegExp(fileNameLower, 'g'), '');
            intent = intent.replace(new RegExp(fileNameWithoutExt, 'g'), '');
        }

        let strategy = "UNKNOWN";
        let search = null;
        let replace = null;
        let confidence = 0.5;
        let functionName = null;

        // Definición de Intenciones Cognitivas (Regex Difusas)
        const removeRegex = /(elimina|borra|remove|delet|quit|destruy)/i;
        const replaceRegex =/(reemplaza|replace|cambia|modifica|updat|actualiz|repara|repair|fix)/i;
        const appendRegex = /(creat|crea|agreg|aggg|add|añad|pon|insert)/i;

        /* ============================================
           EVALUACIÓN DE ESTRATEGIA (Orden de Prioridad)
        ============================================ */
         

        // 0. READ-ONLY ANALYSIS (SIA7 Cognitive Audit)
        if (intent.includes("analiza") || intent.includes("estado") || intent.includes("audit")) {
            strategy = "ANALYZE_ONLY";
            confidence = 1.0;
            
            // Retornamos un parche ficticio que el ejecutor entenderá como "No hacer cambios"
            return {
                ok: true,
                file: targetFile,
                strategy: "ANALYZE_ONLY",
                isReadOnly: true, // Flag para que el ejecutor no toque GitHub
                analysisResult: `El archivo ${targetFile} contiene ${currentSource.length} bytes y está bajo gobierno de zona segura.`
            };
        }
        
        // 1. FUNCTION REMOVE
        if (removeRegex.test(intent)) {
            
            functionName = extractTargetName(intent, removeRegex);
            strategy = "FUNCTION_REMOVE";
            confidence = 0.95;

            const functionRegex = new RegExp(
                `function\\s+${functionName}\\s*\\([^)]*\\)\\s*\\{[\\s\\S]*?\\}`,
                "m"
            );

            const functionMatchFound = currentSource.match(functionRegex);

            console.log(
    "🧪 FUNCTION_CAPTURED",
    functionMatchFound?.[0]
);

            if (functionMatchFound) {
                search = functionMatchFound[0];
                replace = "";
            }

            console.log("🧠 [PATCH_STRATEGY]", strategy, functionName);
        }

        // 2. FUNCTION REPLACE
        else if (replaceRegex.test(intent)) {
            
            functionName = extractTargetName(intent, replaceRegex);
            strategy = "FUNCTION_REPLACE";
            confidence = 0.95;

            const functionRegex = new RegExp(
    `(export\\s+)?function\\s+${functionName}\\s*\\([^)]*\\)\\s*\\{[\\s\\S]*?\\}`,
    "m"
);

            const functionMatchFound = currentSource.match(functionRegex);

            console.log(
    "🧪 FUNCTION_CAPTURED",
    functionMatchFound?.[0]
);

            console.log(
    "🧪 FUNCTION_MATCH_FOUND",
    !!functionMatchFound
);

console.log(
    "🧪 FUNCTION_REGEX",
    functionRegex
);

console.log("🧪 SOURCE_TYPE", typeof currentSource);

console.log("🧪 SOURCE_VALUE", currentSource);

console.log("🧪 USER_INTENT", userIntent);

            if (functionMatchFound) {
                search = functionMatchFound[0];
            }
            

            const originalHeader =
    search.match(/^(export\s+)?(async\s+)?function\s+[a-zA-Z0-9_]+\s*\([^)]*\)/)?.[0];

const preservedHeader =
    originalHeader ||
    `function ${functionName}()`;

replace =
`${preservedHeader} {

    return {
        repaired: true,
        timestamp: Date.now()
    };
}`;

            console.log("🧠 [PATCH_STRATEGY]", strategy, functionName);
        }

        // 3. FUNCTION APPEND
        else if (appendRegex.test(intent)) {
            
            functionName = extractTargetName(intent, appendRegex);
            strategy = "FUNCTION_APPEND";
            confidence = 0.95;

            /* INTELLIGENT INSERTION POINT DETECTION */
            
            /// 🔥 FIX SIA7: Inyección Protegida por Reemplazo de Bloque
            if (currentSource.includes("/* FIXGO_SAFE_EDIT_START */")) {
                strategy = "FUNCTION_APPEND_SAFE_ZONE";
                
                // Buscamos desde el inicio hasta el fin del bloque seguro
                const blockRegex = /\/\* FIXGO_SAFE_EDIT_START \*\/([\s\S]*?)\/\* FIXGO_SAFE_EDIT_END \*\//;
                const match = currentSource.match(blockRegex);
                
                if (match) {
                    search = match[0]; // El bloque completo original
                    replace = 
`/* FIXGO_SAFE_EDIT_START */${match[1]}
function ${functionName}() {
    return {
        ok: true,
        timestamp: Date.now()
    };
}

/* FIXGO_SAFE_EDIT_END */`;
                }
            
            }
            else if (currentSource.includes("export default")) {
                search = "export default";
                replace = 
`export function ${functionName}() {

    return {
        ok: true,
        timestamp: Date.now()
    };
}

export default`;
                strategy = "FUNCTION_APPEND_ESMODULE";
            }
            else if (currentSource.includes("window.")) {
                search = currentSource;
                replace = currentSource + 
`

window.${functionName} = function() {

    return {
        ok: true,
        timestamp: Date.now()
    };
};
`;
                strategy = "FUNCTION_APPEND_WINDOW";
            }
            else {
                search = currentSource;
                replace = currentSource + 
`

function ${functionName}() {

    return {
        ok: true,
        timestamp: Date.now()
    };
}
`;
                strategy = "FUNCTION_APPEND_EOF";
            }

            console.log("🧠 [PATCH_STRATEGY]", strategy, functionName);
        }
        /* ============================================
           EXPORT APPEND (Fallback)
        ============================================ */

        if (!search && currentSource.includes("window.")) {
            strategy = "WINDOW_FUNCTION_APPEND";
            confidence = 0.75;
            search = "\n};";
            replace = 
`\n};

window.runtimeDiagnostic = function() {

    return {
        healthy: true,
        timestamp: Date.now()
    };
};`;
        }

        /* ============================================
           VALIDACIÓN FINAL Y RETORNO
        ============================================ */

        if (!search) {
            return {
                ok: false,
                reason: "NO_REPAIR_STRATEGY",
                file: targetFile,
                intent: userIntent
            };
        }

        const patch = {
            ok: true,
            file: targetFile,
            strategy,
            confidence,
            search,
            replace,
            sourceLength: currentSource.length
        };

        console.log(
            "🧠 [PATCH_READY]",
            patch
        );

        return patch;

    } catch(error) {

        console.error(
            "🚨 [REPAIR_TRANSLATOR_FAIL]",
            error
        );

        return {
            ok: false,
            error: error.message
        };
    }
};

