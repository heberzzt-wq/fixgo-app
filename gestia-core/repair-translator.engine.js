/* ============================================
   SIA7: NLP TARGET EXTRACTOR
   Extrae el nombre de la función tolerando
   typos, faltas de ortografía y palabras de relleno.
============================================ */
function extractTargetName(intentText, actionRegex) {
    if (!actionRegex.test(intentText)) return null;
    
    // Cortamos la cadena a partir de la acción detectada
    let remainder = intentText.substring(intentText.search(actionRegex));
    remainder = remainder.replace(actionRegex, '');
    
    // Limpiamos la "basura" léxica y errores comunes
    remainder = remainder.replace(/\b(la|el|una|un|funci[oó]n|fncion|function|m[eé]todo|de|en|el|archivo|file|script)\b/gi, ' ');
    
    // El primer término limpio que quede debe ser el target
    const words = remainder.trim().split(/\s+/);
    const target = words[0] ? words[0].replace(/[^a-zA-Z0-9_]/g, '') : null;
    
    return target && target.length > 0 ? target : "autoGeneratedSIA7Function";
}

/* ============================================
   SIA7: FUNCTION BLOCK EXTRACTOR
   Captura funciones completas con llaves anidadas.
============================================ */
function findFunctionBlock(source, functionName) {

    if (
        !source ||
        !functionName
    ) {
        return null;
    }

    const headerRegex = new RegExp(
        `(export\\s+)?(async\\s+)?function\\s+${functionName}\\s*\\([^)]*\\)\\s*\\{`,
        "m"
    );

    const headerMatch =
        source.match(headerRegex);

    if (!headerMatch) {
        return null;
    }

    const startIndex =
        headerMatch.index;

    const openBraceIndex =
        source.indexOf(
            "{",
            startIndex
        );

    if (openBraceIndex === -1) {
        return null;
    }

    let depth = 0;

    for (
        let i = openBraceIndex;
        i < source.length;
        i++
    ) {

        const char =
            source[i];

        if (char === "{") {
            depth++;
        }

        if (char === "}") {
            depth--;
        }

        if (depth === 0) {

            return {
                block:
                    source.substring(
                        startIndex,
                        i + 1
                    ),

                header:
                    source.substring(
                        startIndex,
                        openBraceIndex
                    ).trim(),

                start:
                    startIndex,

                end:
                    i + 1
            };
        }
    }

    return null;
}

/* ============================================
   SIA7: SAFE REPLACEMENT BODY BUILDER
   Convierte instrucciones simples en código.
============================================ */

function buildSafeReplacementBody(
    instruction = ""
) {

    const normalized =
        String(instruction)
            .trim();

    const returnMatch =
        normalized.match(
            /(?:retorne|devuelva|regrese|return)\s+(.+)$/i
        );

    if (!returnMatch) {

        return {
            ok: false,
            reason:
                "RETURN_VALUE_REQUIRED"
        };
    }

    let rawValue =
        returnMatch[1]
            .trim()
            .replace(/[.;]+$/, "");

    let expression =
        null;

    /* ============================================
       NUMBER
    ============================================ */

    if (
        /^-?\d+(?:\.\d+)?$/.test(
            rawValue
        )
    ) {

        expression =
            rawValue;
    }

    /* ============================================
       BOOLEAN / NULL
    ============================================ */

    else if (
        /^(true|false|null)$/i.test(
            rawValue
        )
    ) {

        expression =
            rawValue.toLowerCase();
    }

    /* ============================================
       QUOTED STRING
    ============================================ */

    else if (
        /^(['"`])[\s\S]*\1$/.test(
            rawValue
        )
    ) {

        expression =
            rawValue;
    }

    /* ============================================
       SAFE TEXT
       Ejemplo: retorne texto ONLINE
    ============================================ */

    else {

        const textMatch =
            rawValue.match(
                /^texto\s+(.+)$/i
            );

        if (textMatch) {

            expression =
                JSON.stringify(
                    textMatch[1].trim()
                );
        }
    }

    if (!expression) {

        return {
            ok: false,
            reason:
                "UNSUPPORTED_REPLACEMENT_VALUE"
        };
    }

    return {
        ok: true,

        body:
`{

    return ${expression};
}`,

        expression
    };
}


